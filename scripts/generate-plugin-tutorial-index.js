import { mkdir, readdir, readFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dir, "..");
const pluginsRoot = path.resolve(root, "..", "rix", "plugins");
const outputPath = path.join(root, "src", "generated", "plugin-tutorial-index.js");
const tutorialIndexSource = await readFile(path.join(root, "src", "tutorial-index.js"), "utf8");
const coreRootNumbers = [...tutorialIndexSource.matchAll(/\{ number: "(\d+)", file:/g)]
    .map((match) => Number.parseInt(match[1], 10));
const pluginStartNumber = Math.max(0, ...coreRootNumbers) + 1;

const themeOrder = [
    "Numbers and numerics",
    "Algebra and analysis",
    "Graphics and geometry",
    "Data and documents",
    "Renderers and exporters",
    "Higher-dimensional visualization",
];

const themeDescriptions = {
    "Numbers and numerics": "Optional real-number representations, refinement, and numerical algorithms.",
    "Algebra and analysis": "Exact symbolic structures, statistics, and mathematical analysis.",
    "Graphics and geometry": "Portable drawing, plots, constructions, and scene authoring.",
    "Data and documents": "Relations, tables, reports, templates, and publication structure.",
    "Renderers and exporters": "Turn semantic RiX values into portable target formats.",
    "Higher-dimensional visualization": "Three-dimensional, N-dimensional, and complex-function views.",
};

function parseFrontmatter(source) {
    const match = source.match(/^---\n([\s\S]*?)\n---\n?/);
    if (!match) return {};
    return Object.fromEntries(match[1].split("\n").map((line) => {
        const index = line.indexOf(":");
        return index === -1 ? [line.trim(), ""] : [line.slice(0, index).trim(), line.slice(index + 1).trim()];
    }));
}

const discovered = [];
for (const entry of await readdir(pluginsRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const tutorialPath = path.join(pluginsRoot, entry.name, "tutorial.md");
    let source;
    try {
        source = await readFile(tutorialPath, "utf8");
    } catch (error) {
        if (error?.code === "ENOENT") continue;
        throw error;
    }
    const meta = parseFrontmatter(source);
    const theme = meta.theme || "Developer plugins";
    discovered.push({
        pluginId: meta.plugin || entry.name,
        pluginDirectory: entry.name,
        title: meta.title || entry.name,
        description: meta.description || `Learn the optional ${entry.name} plugin.`,
        status: meta.status || "implemented",
        theme,
        sourcePath: path.relative(root, tutorialPath).split(path.sep).join("/"),
    });
}

const presentThemes = [...new Set(discovered.map((tutorial) => tutorial.theme))]
    .sort((left, right) => {
        const leftIndex = themeOrder.indexOf(left);
        const rightIndex = themeOrder.indexOf(right);
        if (leftIndex === -1 && rightIndex === -1) return left.localeCompare(right);
        if (leftIndex === -1) return 1;
        if (rightIndex === -1) return -1;
        return leftIndex - rightIndex;
    });

const pluginTutorialGroups = [];
const pluginTutorials = [];
for (const [groupIndex, theme] of presentThemes.entries()) {
    const number = String(pluginStartNumber + groupIndex);
    const slug = theme.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    pluginTutorialGroups.push({
        number,
        file: `plugins-${slug}.html`,
        title: `Plugins: ${theme}`,
        description: themeDescriptions[theme] || `Optional RiX plugins grouped under ${theme}.`,
        pluginGroup: true,
        theme,
    });
    const children = discovered
        .filter((tutorial) => tutorial.theme === theme)
        .sort((left, right) => left.pluginId.localeCompare(right.pluginId));
    for (const [childIndex, tutorial] of children.entries()) {
        const suffix = String.fromCharCode("a".charCodeAt(0) + childIndex);
        pluginTutorials.push({
            ...tutorial,
            number: `${number}${suffix}`,
            parent: number,
            file: `plugin-${tutorial.pluginId}.html`,
            pluginTutorial: true,
        });
    }
}

await mkdir(path.dirname(outputPath), { recursive: true });
await Bun.write(outputPath, `// Generated by scripts/generate-plugin-tutorial-index.js. Do not edit manually.
export const pluginTutorialGroups = ${JSON.stringify(pluginTutorialGroups, null, 2)};
export const pluginTutorials = ${JSON.stringify(pluginTutorials, null, 2)};
`);
